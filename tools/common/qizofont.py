def pixel(ch, x, y):
    cols = GLYPHS.get(ch)
    if cols is None:
        cols = GLYPHS[ord("?")]
    return bool(cols[x] & (1 << y))


def bitmap(ch):
    rows = []
    for y in range(H):
        v = 0
        for x in range(W):
            if pixel(ch, x, y):
                v |= 1 << (7 - x)
        rows.append(v)
    return rows


def psf1(path):
    data = bytearray()
    data += b"\x72\xb5\x4a\x86"
    data += bytes([0, W, H, 0])
    for ch in range(256):
        src = bitmap(ch + FIRST) if ch < LAST - FIRST + 1 else None
        for y in range(H):
            data.append(src[y])
        for y in range(H, 16):
            data.append(0)
    with open(path, "wb") as f:
        f.write(bytes(data))
    return len(data)


